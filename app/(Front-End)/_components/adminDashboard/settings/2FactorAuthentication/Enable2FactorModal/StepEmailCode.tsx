"use client";

import CustomInput from "@/components/reusable/dashboard/CustomInput";
import Loading from "@/components/reusable/Loader";
import { useProviderEmailCodeMutation } from "@/feature/slice/admin/securitySettings";
import { useState } from "react";
import toast from "react-hot-toast";

interface StepEmailCodeProps {
  onSuccess: (codes: string[]) => void;
  onBack: () => void;
  onClose: () => void;
}

export default function StepEmailCode({
  onSuccess,
  onBack,
  onClose,
}: StepEmailCodeProps) {
  const [code, setCode] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

   const [providerEmailCode,{isLoading}] = useProviderEmailCodeMutation();

const handleSubmit = (e: React.FormEvent) => {
  e.preventDefault();
  setError("");

  providerEmailCode({ code })
    .unwrap()
    .then((res) => {
      toast.success(res.message);
      onSuccess(res.recovery_codes || []);
    })
    .catch((err) => setError(err?.data?.message || "Invalid code"));
};
  return (
    <form onSubmit={handleSubmit} className="space-y-4 px-3">
      <p className="text-sm text-[#777980]">
       Enter the 6-digit code generated by your Authenticator app

      </p>

       <p className="text-sm text-[#777980]">
        <p className="text-sm text-[#777980]">
     Note: You can also copy the code by tapping on it and pasting into the LinkedIn app


      </p>

      </p>

      <CustomInput
       
        type="text"
        required
        value={code}
        onChange={(e) => setCode(e.target.value)}
        placeholder="Enter 6-digit code"
        maxLength={6}
        error={error}
        className="text-center tracking-widest text-lg"
      />

      {/* <button type="button" className="text-sm font-medium text-primaryColor">
        Resend Code
      </button> */}

      <div className="flex flex-col-reverse  gap-3 pt-2">
     
        <button
          type="button"
          onClick={onBack}
          className="rounded-md border px-4 cursor-pointer py-2 text-sm font-medium"
        >
          Back to Setup
        </button>
         {
          isLoading?(
            <Loading/>
          ):(
                <button
          type="submit"
          disabled={loading}
          className="rounded-md bg-primaryColor cursor-pointer px-4 py-2 text-sm font-medium text-white disabled:opacity-60"
        >
          {loading ? "Confirming..." : "Confirm"}
        </button>
          )
         }
      
      </div>
    </form>
  );
}